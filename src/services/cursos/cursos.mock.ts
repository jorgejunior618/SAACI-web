const horas = (complemento: string): Item['unidade'] => ({ tipo: 'horas', complemento })
const contagem = (singular: string, plural: string): Item['unidade'] => ({
  tipo: 'contagem',
  singular,
  plural,
})
const qualis: Item['unidade'] = { tipo: 'qualis' }

const itemQualis = (
  numero: number,
  nome: string,
  nomeCurto: string,
  horasBase: number,
  limite: number,
): Item => ({
  numero,
  nome,
  nomeCurto,
  regraResumo: `${horasBase}h vezes o fator Qualis, até ${limite}h`,
  regraTexto: `Cada trabalho conta ${horasBase}h multiplicadas pelo fator Qualis do evento ou periódico. A soma deste item vai até ${limite}h.`,
  limite,
  unidade: qualis,
  conversao: { horas: horasBase, por: 1 },
  campoQuantidade: 'Fator Qualis',
  dicaQuantidade: 'Está na classificação Qualis do evento ou periódico, por exemplo 1 ou 0,85.',
})

